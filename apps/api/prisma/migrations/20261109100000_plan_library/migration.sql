-- The plan library: reference project plans (phase / task / subtask) that every
-- organization can read, and each organization's own private copies.
--
-- The reference tables carry no `organization_id` and are written only by
-- migrations. Private plans do, on both tables, so the tenant filter covers
-- them whichever one a query starts from.
--
-- Content: common practice in the trade, not a Tunisian official standard.
-- See docs/16-bibliotheque-plans.md for its sources and limits.

CREATE TYPE "public"."worksite_kind" AS ENUM ('building', 'roads', 'networks', 'earthworks', 'other');
CREATE TYPE "public"."plan_node_level" AS ENUM ('phase', 'task', 'subtask');

CREATE TABLE "public"."plan_templates" (
  "code" TEXT NOT NULL,
  "kind" "public"."worksite_kind" NOT NULL,
  "sort_order" INTEGER NOT NULL,
  CONSTRAINT "pk_plan_templates" PRIMARY KEY ("code")
);

CREATE TABLE "public"."plan_template_translations" (
  "template_code" TEXT NOT NULL,
  "locale" TEXT NOT NULL,
  "label" TEXT NOT NULL,
  CONSTRAINT "pk_plan_template_translations" PRIMARY KEY ("template_code", "locale"),
  CONSTRAINT "fk_plan_template_translations_plan_templates" FOREIGN KEY ("template_code") REFERENCES "public"."plan_templates"("code") ON DELETE CASCADE ON UPDATE CASCADE
);

CREATE TABLE "public"."plan_template_nodes" (
  "code" TEXT NOT NULL,
  "template_code" TEXT NOT NULL,
  "parent_code" TEXT,
  "level" "public"."plan_node_level" NOT NULL,
  "sort_order" INTEGER NOT NULL,
  "is_control" BOOLEAN NOT NULL DEFAULT false,
  CONSTRAINT "pk_plan_template_nodes" PRIMARY KEY ("code"),
  CONSTRAINT "fk_plan_template_nodes_plan_templates" FOREIGN KEY ("template_code") REFERENCES "public"."plan_templates"("code") ON DELETE CASCADE ON UPDATE CASCADE,
  CONSTRAINT "fk_plan_template_nodes_parent" FOREIGN KEY ("parent_code") REFERENCES "public"."plan_template_nodes"("code") ON DELETE CASCADE ON UPDATE CASCADE
);
CREATE INDEX "ix_plan_template_nodes_template_code" ON "public"."plan_template_nodes"("template_code");
CREATE INDEX "ix_plan_template_nodes_parent_code" ON "public"."plan_template_nodes"("parent_code");

CREATE TABLE "public"."plan_template_node_translations" (
  "node_code" TEXT NOT NULL,
  "locale" TEXT NOT NULL,
  "label" TEXT NOT NULL,
  CONSTRAINT "pk_plan_template_node_translations" PRIMARY KEY ("node_code", "locale"),
  CONSTRAINT "fk_plan_template_node_translations_plan_template_nodes" FOREIGN KEY ("node_code") REFERENCES "public"."plan_template_nodes"("code") ON DELETE CASCADE ON UPDATE CASCADE
);

CREATE TABLE "public"."organization_plans" (
  "id" UUID NOT NULL,
  "organization_id" UUID NOT NULL,
  "source_template_code" TEXT,
  "name" TEXT NOT NULL,
  "kind" "public"."worksite_kind" NOT NULL,
  "created_at" TIMESTAMP(3) NOT NULL DEFAULT CURRENT_TIMESTAMP,
  "updated_at" TIMESTAMP(3) NOT NULL,
  CONSTRAINT "pk_organization_plans" PRIMARY KEY ("id"),
  CONSTRAINT "fk_organization_plans_plan_templates" FOREIGN KEY ("source_template_code") REFERENCES "public"."plan_templates"("code") ON DELETE SET NULL ON UPDATE CASCADE
);
CREATE INDEX "ix_organization_plans_organization_id" ON "public"."organization_plans"("organization_id");

CREATE TABLE "public"."organization_plan_nodes" (
  "id" UUID NOT NULL,
  "organization_id" UUID NOT NULL,
  "plan_id" UUID NOT NULL,
  "parent_id" UUID,
  "level" "public"."plan_node_level" NOT NULL,
  "label" TEXT NOT NULL,
  "sort_order" INTEGER NOT NULL,
  "is_control" BOOLEAN NOT NULL DEFAULT false,
  CONSTRAINT "pk_organization_plan_nodes" PRIMARY KEY ("id"),
  CONSTRAINT "fk_organization_plan_nodes_organization_plans" FOREIGN KEY ("plan_id") REFERENCES "public"."organization_plans"("id") ON DELETE CASCADE ON UPDATE CASCADE,
  CONSTRAINT "fk_organization_plan_nodes_parent" FOREIGN KEY ("parent_id") REFERENCES "public"."organization_plan_nodes"("id") ON DELETE CASCADE ON UPDATE CASCADE
);
CREATE INDEX "ix_organization_plan_nodes_organization_id" ON "public"."organization_plan_nodes"("organization_id");
CREATE INDEX "ix_organization_plan_nodes_plan_id" ON "public"."organization_plan_nodes"("plan_id");
CREATE INDEX "ix_organization_plan_nodes_parent_id" ON "public"."organization_plan_nodes"("parent_id");

